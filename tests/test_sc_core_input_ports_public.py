"""Compare sc_in constructor, event, lifecycle and trace behavior with C++."""

import os
import subprocess
import sys

from .support import ROOT, run_example


def run_native(tmp_path, *arguments):
    """Build and run the standalone native input-port reference with a timeout.

    Args:
        tmp_path: Isolated directory for native compilation and VCD output.
        arguments: Optional reference modes such as ``--errors``.

    Returns:
        Captured native standard output.

    Raises:
        AssertionError: If compilation or simulation returns a failure status.
        subprocess.TimeoutExpired: If native execution exceeds sixty seconds.
    """
    env = dict(os.environ, SYSTEMC_HOME=os.environ.get("SYSTEMC_HOME", str(ROOT / "submodules/systemc")))
    command = [
        sys.executable,
        str(ROOT / "examples/run_sysc_cpp.py"),
        str(ROOT / "tests/native/sc_core_input_ports_public.cpp"),
    ]
    if arguments:
        command.extend(("--", *arguments))
    result = subprocess.run(
        command,
        cwd=tmp_path,
        env=env,
        capture_output=True,
        text=True,
        timeout=60,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    return result.stdout


def read_trace(path):
    """Map VCD declarations and sampled transitions by signal name.

    Args:
        path: VCD file generated by a Python or native input-port model.

    Returns:
        Signal widths and (time, value) transitions keyed by declaration name.
    """
    contents = path.read_text(encoding="utf-8").splitlines()
    code_to_name = {}
    widths = {}
    for line in contents:
        if line.startswith("$var"):
            parts = line.split()
            code_to_name[parts[3]] = parts[4]
            widths[parts[4]] = int(parts[2])
    transitions = {name: [] for name in widths}
    timestamp = "0"
    for line in contents:
        if line.startswith("#"):
            timestamp = line[1:]
        elif line.startswith("b"):
            value, code = line.split()
            transitions[code_to_name[code]].append((timestamp, value[1:]))
        elif line.startswith(("0", "1", "x", "z")):
            value, code = line[0], line[1:]
            if code in code_to_name:
                transitions[code_to_name[code]].append((timestamp, value))
    return widths, transitions


def test_sc_in_public_families(tmp_path):
    """Verify generic and specialized inputs against constructors and a live VCD."""
    python_dir = tmp_path / "python"
    native_dir = tmp_path / "native"
    python_dir.mkdir()
    native_dir.mkdir()

    python_output = run_example(python_dir, "tests/models/sc_core_input_ports_public.py")
    native_output = run_native(native_dir)
    marker = "INPUT_PORT_"
    python_lines = [line for line in python_output.splitlines() if line.startswith(marker)]
    native_lines = [line for line in native_output.splitlines() if line.startswith(marker)]
    assert python_lines == native_lines, (python_lines, native_lines)

    python_widths, python_transitions = read_trace(python_dir / "sc_core_input_ports_public.vcd")
    native_widths, native_transitions = read_trace(native_dir / "sc_core_input_ports_public.vcd")
    expected_widths = {
        "wide_input": 137,
        "bool_input": 1,
        "logic_input": 1,
        "wide_member": 137,
        "bool_member": 1,
        "logic_member": 1,
    }
    assert python_widths == native_widths == expected_widths
    assert python_transitions == native_transitions
    assert python_transitions["wide_input"]
    assert [time for time, _ in python_transitions["wide_input"]] == ["0", "1"]
    assert [time for time, _ in python_transitions["bool_input"]] == ["0", "1"]
    assert [time for time, _ in python_transitions["logic_input"]] == ["0", "1"]


def test_sc_in_unbound_required_error(tmp_path):
    """Check required input binding errors in separate Python and native kernels."""
    python_dir = tmp_path / "python"
    native_dir = tmp_path / "native"
    python_dir.mkdir()
    native_dir.mkdir()

    python_output = run_example(python_dir, "tests/models/sc_core_input_ports_public.py", ("--errors",))
    native_output = run_native(native_dir, "--errors")
    assert "INPUT_PORT_ERRORS|unbound-required" in python_output
    assert "INPUT_PORT_ERRORS|unbound-required" in native_output
