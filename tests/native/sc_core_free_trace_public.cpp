/** @file sc_core_free_trace_public.cpp
 * @brief Independent native free-tracing overload and waveform reference.
 */
#include "sc_core_free_trace_probe.h"
/** @brief Check reference/pointer dispatch and pre-elaboration port waveforms. */
int sc_main(int, char**)
{
  using namespace sc_core;
  TraceFileProbe file;
  sc_trace(&file, file.event_sample(), "event_ref");
  sc_trace(&file, free_trace_probe::event_pointer(file), "event_ptr");
  sc_trace(&file, file.time_sample(), "time_ref");
  sc_trace(&file, free_trace_probe::time_pointer(file), "time_ptr");
  sc_trace(&file, file.bool_sample(), "bool_ref");
  sc_trace(&file, free_trace_probe::bool_pointer(file), "bool_ptr");
  sc_trace(&file, file.float_sample(), "float_ref");
  sc_trace(&file, free_trace_probe::float_pointer(file), "float_ptr");
  sc_trace(&file, file.double_sample(), "double_ref");
  sc_trace(&file, free_trace_probe::double_pointer(file), "double_ptr");
  sc_trace(&file, file.bit_sample(), "bit_ref");
  sc_trace(&file, free_trace_probe::bit_pointer(file), "bit_ptr");
  sc_trace(&file, file.logic_sample(), "logic_ref");
  sc_trace(&file, free_trace_probe::logic_pointer(file), "logic_ptr");
  sc_trace(&file, file.sc_int_sample(), "sc_int_ref");
  sc_trace(&file, free_trace_probe::sc_int_pointer(file), "sc_int_ptr");
  sc_trace(&file, file.sc_uint_sample(), "sc_uint_ref");
  sc_trace(&file, free_trace_probe::sc_uint_pointer(file), "sc_uint_ptr");
  sc_trace(&file, file.signed_wide_sample(), "signed_wide_ref");
  sc_trace(&file, free_trace_probe::signed_wide_pointer(file), "signed_wide_ptr");
  sc_trace(&file, file.unsigned_wide_sample(), "unsigned_wide_ref");
  sc_trace(&file, free_trace_probe::unsigned_wide_pointer(file), "unsigned_wide_ptr");
  sc_trace(&file, file.bits_sample(), "bits_ref");
  sc_trace(&file, free_trace_probe::bits_pointer(file), "bits_ptr");
  sc_trace(&file, file.logic_vector_sample(), "logic_vector_ref");
  sc_trace(&file, free_trace_probe::logic_vector_pointer(file), "logic_vector_ptr");
  sc_trace(&file, file.fxval_sample(), "fxval_ref");
  sc_trace(&file, free_trace_probe::fxval_pointer(file), "fxval_ptr");
  sc_trace(&file, file.fxval_fast_sample(), "fxval_fast_ref");
  sc_trace(&file, free_trace_probe::fxval_fast_pointer(file), "fxval_fast_ptr");
  sc_trace(&file, file.fixed_sample(), "fixed_ref");
  sc_trace(&file, free_trace_probe::fixed_pointer(file), "fixed_ptr");
  sc_trace(&file, file.fixed_fast_sample(), "fixed_fast_ref");
  sc_trace(&file, free_trace_probe::fixed_fast_pointer(file), "fixed_fast_ptr");
  sc_trace(&file, file.uchar_sample(), "uchar_ref", 7);
  sc_trace(&file, file.uchar_sample(), "uchar_ref_default");
  sc_trace(&file, free_trace_probe::uchar_pointer(file), "uchar_ptr", 9);
  sc_trace(&file, free_trace_probe::uchar_pointer(file), "uchar_ptr_default");
  sc_trace(&file, file.ushort_sample(), "ushort_ref", 8);
  sc_trace(&file, file.ushort_sample(), "ushort_ref_default");
  sc_trace(&file, free_trace_probe::ushort_pointer(file), "ushort_ptr", 10);
  sc_trace(&file, free_trace_probe::ushort_pointer(file), "ushort_ptr_default");
  sc_trace(&file, file.uint_sample(), "uint_ref", 9);
  sc_trace(&file, file.uint_sample(), "uint_ref_default");
  sc_trace(&file, free_trace_probe::uint_pointer(file), "uint_ptr", 11);
  sc_trace(&file, free_trace_probe::uint_pointer(file), "uint_ptr_default");
  sc_trace(&file, file.ulong_sample(), "ulong_ref", 10);
  sc_trace(&file, file.ulong_sample(), "ulong_ref_default");
  sc_trace(&file, free_trace_probe::ulong_pointer(file), "ulong_ptr", 12);
  sc_trace(&file, free_trace_probe::ulong_pointer(file), "ulong_ptr_default");
  sc_trace(&file, file.char_sample(), "char_ref", 11);
  sc_trace(&file, file.char_sample(), "char_ref_default");
  sc_trace(&file, free_trace_probe::char_pointer(file), "char_ptr", 13);
  sc_trace(&file, free_trace_probe::char_pointer(file), "char_ptr_default");
  sc_trace(&file, file.short_sample(), "short_ref", 12);
  sc_trace(&file, file.short_sample(), "short_ref_default");
  sc_trace(&file, free_trace_probe::short_pointer(file), "short_ptr", 14);
  sc_trace(&file, free_trace_probe::short_pointer(file), "short_ptr_default");
  sc_trace(&file, file.int_sample(), "int_ref", 13);
  sc_trace(&file, file.int_sample(), "int_ref_default");
  sc_trace(&file, free_trace_probe::int_pointer(file), "int_ptr", 15);
  sc_trace(&file, free_trace_probe::int_pointer(file), "int_ptr_default");
  sc_trace(&file, file.long_sample(), "long_ref", 14);
  sc_trace(&file, file.long_sample(), "long_ref_default");
  sc_trace(&file, free_trace_probe::long_pointer(file), "long_ptr", 16);
  sc_trace(&file, free_trace_probe::long_pointer(file), "long_ptr_default");
  sc_trace(&file, file.int64_sample(), "int64_ref", 15);
  sc_trace(&file, file.int64_sample(), "int64_ref_default");
  sc_trace(&file, free_trace_probe::int64_pointer(file), "int64_ptr", 17);
  sc_trace(&file, free_trace_probe::int64_pointer(file), "int64_ptr_default");
  sc_trace(&file, file.uint64_sample(), "uint64_ref", 16);
  sc_trace(&file, file.uint64_sample(), "uint64_ref_default");
  sc_trace(&file, free_trace_probe::uint64_pointer(file), "uint64_ptr", 18);
  sc_trace(&file, free_trace_probe::uint64_pointer(file), "uint64_ptr_default");
  unsigned int state = 1;
  const char* names[] = {"IDLE", "BUSY", nullptr};
  sc_trace(&file, state, "enum", names);
  const int warning_count = sc_report_handler::get_count(SC_WARNING);
  sc_report_handler::set_actions(SC_WARNING, SC_DO_NOTHING);
  sc_trace(&file, static_cast<const void*>(nullptr), "ignored");
  if (sc_report_handler::get_count(SC_WARNING) != warning_count + 1) return 2;
  std::cout << "FREE_TRACE_IGNORED 1\n";
  sc_report_handler::set_actions(SC_WARNING, SC_DISPLAY);
  sc_trace(nullptr, static_cast<const float*>(nullptr), "null");
  sc_signal<char> signal_char("signal_char", 5);
  sc_trace(&file, signal_char, "signal_char", 6);
  sc_signal<short> signal_short("signal_short", 5);
  sc_trace(&file, signal_short, "signal_short", 7);
  sc_signal<int> signal_int("signal_int", 5);
  sc_trace(&file, signal_int, "signal_int", 8);
  sc_signal<long> signal_long("signal_long", 5);
  sc_trace(&file, signal_long, "signal_long", 9);
  sc_signal<float> floating("floating", 1.25f);
  sc_trace(&file, floating, std::string("floating_string"));
  sc_trace(&file, static_cast<const sc_signal_in_if<float>&>(floating), "floating_chars");
  for (const auto& row : file.records()) std::cout << "FREE_TRACE|" << row << '\n';
  sc_signal<int> integer("integer", 3);
  sc_signal<sc_dt::sc_biguint<137>> wide("wide", 17);
  free_trace_probe::ports ports("ports");
  auto* wave = sc_create_vcd_trace_file("native_free_trace");
  wave->set_time_unit(1, SC_PS);
  sc_trace(wave, ports.input, "input_before_bind");
  sc_trace(wave, ports.inout, "inout_before_bind");
  sc_trace(wave, ports.wide_input, "wide_input_before_bind");
  sc_trace(wave, ports.wide_inout, "wide_inout_before_bind");
  sc_trace(wave, free_trace_probe::char_pointer(file), "char_pointer_wave");
  sc_trace(wave, free_trace_probe::char_pointer(file), "char_array_wave");
  ports.input.bind(integer);
  ports.inout.bind(integer);
  ports.wide_input.bind(wide);
  ports.wide_inout.bind(wide);
  sc_trace(wave, integer, "integer_width", 7);
  sc_trace(wave, wide, "wide_generic");
  sc_start(1, SC_NS);
  file.char_sample() = static_cast<char>(0xff);
  sc_trace(&file, ports.input, "input_after_elaboration");
  sc_trace(&file, ports.inout, "inout_after_elaboration");
  for (std::size_t index = 81; index < file.records().size(); ++index)
    std::cout << "FREE_TRACE|" << file.records()[index] << '\n';
  integer.write(35);
  wide.write(sc_dt::sc_biguint<137>("87112285931760246646623899502532662132993"));
  sc_start(1, SC_NS);
  sc_close_vcd_trace_file(wave);
  std::cout << "FREE_TRACE_TIME " << sc_time_stamp().value() << '\n';
  return 0;
}
