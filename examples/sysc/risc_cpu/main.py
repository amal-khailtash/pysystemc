"""Python top-level port of Accellera sysc/risc_cpu/main.cpp.

Apache-2.0; upstream LICENSE/NOTICE. All ten CPU components are Python implementations. Python constructs all signals, clocks and module bindings.
Run in a directory containing bios.img, icache.img, dcache.img and register.img.
"""

from pathlib import Path
import sys
from amal.eda.systemc import sc_core as sc
from decode import Decode
from bios import BIOS as PythonBIOS
from pic import PIC
from paging import Paging
from dcache import DCache
from icache import ICache
from fetch import Fetch
from exec import Execute
from mmxu import MMX
from floating import Floating


def run():
    """Instantiate the Python CPU with native SystemC ports and verify its terminal simulation.

    Returns:
        None after native instruction shutdown message at 274 ns and stop at 275 ns for default images.
    Raises:
        FileNotFoundError: A required image file is absent.
        RuntimeError: Binding of a component fails.
    Python components and native signal storage remain retained until shutdown. Independent
    runs require fresh interpreters; all process callbacks are Python.
    """
    sys.stdout.reconfigure(line_buffering=True)
    for image in ("bios.img", "icache.img", "dcache.img", "register.img"):
        if not Path(image).is_file():
            raise FileNotFoundError(image)
    sc.sc_report_handler.set_actions("/IEEE_Std_1666/deprecated", sc.SC_DO_NOTHING)
    modules = []
    icache_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("ICACHE_VALID")
    ram_cs = sc.sc_signal["bool", sc.SC_ONE_WRITER]("RAM_CS")
    ram_we = sc.sc_signal["bool", sc.SC_ONE_WRITER]("RAM_WE")
    addr = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("Address")
    ram_datain = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("RAM_DATAIN")
    ram_dataout = sc.sc_signal["unsigned int", sc.SC_MANY_WRITERS]("RAM_DATAOUT")
    bios_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("BIOS_VALID")
    icache_din = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("ICACHE_DIN")
    icache_validin = sc.sc_signal["bool", sc.SC_ONE_WRITER]("ICACHE_VALIDIN")
    icache_stall = sc.sc_signal["bool", sc.SC_ONE_WRITER]("ICACHE_STALL")
    paging_dout = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("PAGING_DOUT")
    paging_csout = sc.sc_signal["bool", sc.SC_ONE_WRITER]("PAGING_CSOUT")
    paging_weout = sc.sc_signal["bool", sc.SC_ONE_WRITER]("PAGING_WEOUT")
    physical_address = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("PHYSICAL_ADDRESS")
    branch_target_address = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("BRANCH_TARGET_ADDRESS")
    next_pc = sc.sc_signal["bool", sc.SC_ONE_WRITER]("NEXT_PC")
    branch_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("BRANCH_VALID")
    stall_fetch = sc.sc_signal["bool", sc.SC_MANY_WRITERS]("STALL_FETCH")
    pred_fetch = sc.sc_signal["bool", sc.SC_ONE_WRITER]("PRED_FETCH")
    instruction = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("INSTRUCTION")
    instruction_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("INSTRUCTION_VALID")
    program_counter = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("PROGRAM_COUNTER")
    branch_clear = sc.sc_signal["bool", sc.SC_ONE_WRITER]("BRANCH_CLEAR")
    pred_fetch_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("PRED_FETCH_VALID")
    reset = sc.sc_signal["bool", sc.SC_ONE_WRITER]("RESET")
    pred_branch_address = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("PRED_BRANCH_ADDRESS")
    pred_branch_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("PRED_BRANCH_VALID")
    pred_tellid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("PRED_TELLID")
    pred_instruction = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("PRED_INSTRUCTION")
    pred_inst_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("PRED_INST_VALID")
    pred_inst_pc = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("PRED_INST_PC")
    pred_on = sc.sc_signal["bool", sc.SC_ONE_WRITER]("PRED_ON")
    branch_instruction_address = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("BR_INSTRUCTION_ADDRESS")
    dram_dataout = sc.sc_signal["int", sc.SC_ONE_WRITER]("DRAM_DATAOUT")
    dram_rd_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("DRAM_RD_VALID")
    dram_write_src = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("DRAM_WRITE_SRC")
    mem_access = sc.sc_signal["bool", sc.SC_ONE_WRITER]("MEM_ACCESS")
    mem_address = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("MEM_ADDRESS")
    alu_op = sc.sc_signal["int", sc.SC_ONE_WRITER]("ALU_OP")
    mem_write = sc.sc_signal["bool", sc.SC_ONE_WRITER]("MEM_WRITE")
    alu_src = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("ALU_SRC")
    reg_write = sc.sc_signal["bool", sc.SC_ONE_WRITER]("REG_WRITE")
    src_A = sc.sc_signal["int", sc.SC_ONE_WRITER]("SRC_A")
    src_B = sc.sc_signal["int", sc.SC_ONE_WRITER]("SRC_B")
    forward_A = sc.sc_signal["bool", sc.SC_ONE_WRITER]("FORWARD_A")
    forward_B = sc.sc_signal["bool", sc.SC_ONE_WRITER]("FORWARD_B")
    decode_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("DECODE_VALID")
    float_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("FLOAT_VALID")
    mmx_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("MMX_VALID")
    pid_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("PID_VALID")
    pid_data = sc.sc_signal["int", sc.SC_ONE_WRITER]("PID_DATA")
    mmic_datain = sc.sc_signal["int", sc.SC_ONE_WRITER]("MMIC_DATAIN")
    mmic_statein = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("MMIC_STATEIN")
    mmic_cs = sc.sc_signal["bool", sc.SC_ONE_WRITER]("MMIC_CS")
    mmic_we = sc.sc_signal["bool", sc.SC_ONE_WRITER]("MMIC_WE")
    mmic_addr = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("MMIC_ADDR")
    mmic_dest = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("MMIC_DEST")
    mmic_destout = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("MMIC_DESTOUT")
    mmic_dataout = sc.sc_signal["int", sc.SC_ONE_WRITER]("MMIC_DATAOUT")
    mmic_out_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("MMIC_OUT_VALID")
    mmic_stateout = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("MMIC_STATEOUT")
    in_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("IN_VALID")
    negate = sc.sc_signal["bool", sc.SC_ONE_WRITER]("NEGATE")
    add1 = sc.sc_signal["int", sc.SC_ONE_WRITER]("ADD1")
    shift_sel = sc.sc_signal["bool", sc.SC_ONE_WRITER]("SHIFT_SEL")
    c = sc.sc_signal["bool", sc.SC_ONE_WRITER]("C")
    v = sc.sc_signal["bool", sc.SC_ONE_WRITER]("V")
    z = sc.sc_signal["bool", sc.SC_ONE_WRITER]("Z")
    dout = sc.sc_signal["int", sc.SC_ONE_WRITER]("DOUT")
    out_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("OUTPUT_VALID")
    destout = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("DESTOUT")
    fdout = sc.sc_signal["int", sc.SC_MANY_WRITERS]("FDOUT")
    fout_valid = sc.sc_signal["bool", sc.SC_MANY_WRITERS]("FOUT_VALID")
    fdestout = sc.sc_signal["unsigned int", sc.SC_MANY_WRITERS]("FDESTOUT")
    ireq0 = sc.sc_signal["bool", sc.SC_ONE_WRITER]("IREQ0")
    ireq1 = sc.sc_signal["bool", sc.SC_ONE_WRITER]("IREQ1")
    ireq2 = sc.sc_signal["bool", sc.SC_ONE_WRITER]("IREQ2")
    ireq3 = sc.sc_signal["bool", sc.SC_ONE_WRITER]("IREQ3")
    rd_wr = sc.sc_signal["bool", sc.SC_ONE_WRITER]("RD_WR")
    intreq = sc.sc_signal["bool", sc.SC_ONE_WRITER]("INTREQ")
    vectno = sc.sc_signal["unsigned int", sc.SC_ONE_WRITER]("VECTNO")
    intack = sc.sc_signal["bool", sc.SC_ONE_WRITER]("INTACK")
    intack_cpu = sc.sc_signal["bool", sc.SC_ONE_WRITER]("INTACK_CPU")
    dsp_in1 = sc.sc_signal["int", sc.SC_ONE_WRITER]("DPS_IN1")
    dsp_out1 = sc.sc_signal["int", sc.SC_ONE_WRITER]("DSP_OUT1")
    dsp_data_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("DSP_DATA_VALID")
    dsp_input_valid = sc.sc_signal["bool", sc.SC_ONE_WRITER]("DSP_INPUT_VALID")
    dsp_data_requested = sc.sc_signal["bool", sc.SC_ONE_WRITER]("DSP_DATA_REQUESTED")
    unused_signals = [
        pred_tellid,
        pred_inst_pc,
        dram_write_src,
        in_valid,
        dsp_in1,
        dsp_out1,
        dsp_input_valid,
        dsp_data_requested,
    ]
    clk = sc.sc_clock("clk")
    IFU = Fetch("FETCH_BLOCK")
    modules.append(IFU)
    IFU.init_param(2)
    IFU.ramdata.bind(ram_dataout)
    IFU.branch_address.bind(branch_target_address)
    IFU.next_pc.bind(next_pc)
    IFU.branch_valid.bind(branch_valid)
    IFU.stall_fetch.bind(stall_fetch)
    IFU.interrupt.bind(intreq)
    IFU.int_vectno.bind(vectno)
    IFU.bios_valid.bind(bios_valid)
    IFU.icache_valid.bind(icache_valid)
    IFU.pred_fetch.bind(pred_fetch)
    IFU.pred_branch_address.bind(pred_branch_address)
    IFU.pred_branch_valid.bind(pred_branch_valid)
    IFU.ram_cs.bind(ram_cs)
    IFU.ram_we.bind(ram_we)
    IFU.address.bind(addr)
    IFU.smc_instruction.bind(ram_datain)
    IFU.instruction.bind(instruction)
    IFU.instruction_valid.bind(instruction_valid)
    IFU.program_counter.bind(program_counter)
    IFU.interrupt_ack.bind(intack_cpu)
    IFU.branch_clear.bind(branch_clear)
    IFU.pred_fetch_valid.bind(pred_fetch_valid)
    IFU.reset.bind(reset)
    IFU.CLK.bind(clk)
    IDU = Decode("DECODE_BLOCK")
    modules.append(IDU)
    IDU.resetin.bind(reset)
    IDU.instruction.bind(instruction)
    IDU.pred_instruction.bind(pred_instruction)
    IDU.instruction_valid.bind(instruction_valid)
    IDU.pred_inst_valid.bind(pred_inst_valid)
    IDU.destreg_write.bind(out_valid)
    IDU.destreg_write_src.bind(destout)
    IDU.alu_dataout.bind(dout)
    IDU.dram_dataout.bind(dram_dataout)
    IDU.dram_rd_valid.bind(dram_rd_valid)
    IDU.dram_write_src.bind(destout)
    IDU.fpu_dout.bind(fdout)
    IDU.fpu_valid.bind(fout_valid)
    IDU.fpu_destout.bind(fdestout)
    IDU.clear_branch.bind(branch_clear)
    IDU.display_done.bind(dsp_data_valid)
    IDU.pc.bind(program_counter)
    IDU.pred_on.bind(pred_on)
    IDU.br_instruction_address.bind(branch_instruction_address)
    IDU.next_pc.bind(next_pc)
    IDU.branch_valid.bind(branch_valid)
    IDU.branch_target_address.bind(branch_target_address)
    IDU.mem_access.bind(mem_access)
    IDU.mem_address.bind(mem_address)
    IDU.alu_op.bind(alu_op)
    IDU.mem_write.bind(mem_write)
    IDU.alu_src.bind(alu_src)
    IDU.reg_write.bind(reg_write)
    IDU.src_A.bind(src_A)
    IDU.src_B.bind(src_B)
    IDU.forward_A.bind(forward_A)
    IDU.forward_B.bind(forward_B)
    IDU.stall_fetch.bind(stall_fetch)
    IDU.decode_valid.bind(decode_valid)
    IDU.float_valid.bind(float_valid)
    IDU.mmx_valid.bind(mmx_valid)
    IDU.pid_valid.bind(pid_valid)
    IDU.pid_data.bind(pid_data)
    IDU.CLK.bind(clk)
    IEU = Execute("EXEC_BLOCK")
    modules.append(IEU)
    IEU.reset.bind(reset)
    IEU.in_valid.bind(decode_valid)
    IEU.opcode.bind(alu_op)
    IEU.negate.bind(negate)
    IEU.add1.bind(add1)
    IEU.shift_sel.bind(shift_sel)
    IEU.dina.bind(src_A)
    IEU.dinb.bind(src_B)
    IEU.forward_A.bind(forward_A)
    IEU.forward_B.bind(forward_B)
    IEU.dest.bind(alu_src)
    IEU.C.bind(c)
    IEU.V.bind(v)
    IEU.Z.bind(z)
    IEU.dout.bind(dout)
    IEU.out_valid.bind(out_valid)
    IEU.destout.bind(destout)
    IEU.CLK.bind(clk)
    FPU = Floating("FLOAT_BLOCK")
    modules.append(FPU)
    FPU.in_valid.bind(float_valid)
    FPU.opcode.bind(alu_op)
    FPU.floata.bind(src_A)
    FPU.floatb.bind(src_B)
    FPU.dest.bind(alu_src)
    FPU.fdout.bind(fdout)
    FPU.fout_valid.bind(fout_valid)
    FPU.fdestout.bind(fdestout)
    FPU.CLK.bind(clk)
    MMXU = MMX("MMX_BLOCK")
    modules.append(MMXU)
    MMXU.mmx_valid.bind(mmx_valid)
    MMXU.opcode.bind(alu_op)
    MMXU.mmxa.bind(src_A)
    MMXU.mmxb.bind(src_B)
    MMXU.dest.bind(alu_src)
    MMXU.mmxdout.bind(fdout)
    MMXU.mmxout_valid.bind(fout_valid)
    MMXU.mmxdestout.bind(fdestout)
    MMXU.CLK.bind(clk)
    BIOS = PythonBIOS("BIOS_BLOCK")
    modules.append(BIOS)
    BIOS.init_param(2)
    BIOS.datain.bind(ram_datain)
    BIOS.cs.bind(ram_cs)
    BIOS.we.bind(ram_we)
    BIOS.addr.bind(addr)
    BIOS.dataout.bind(ram_dataout)
    BIOS.bios_valid.bind(bios_valid)
    BIOS.stall_fetch.bind(stall_fetch)
    BIOS.CLK.bind(clk)
    PAGING = Paging("PAGING_BLOCK")
    modules.append(PAGING)
    PAGING.paging_din.bind(ram_datain)
    PAGING.paging_csin.bind(ram_cs)
    PAGING.paging_wein.bind(ram_we)
    PAGING.logical_address.bind(addr)
    PAGING.icache_din.bind(icache_din)
    PAGING.icache_validin.bind(icache_validin)
    PAGING.icache_stall.bind(icache_stall)
    PAGING.paging_dout.bind(paging_dout)
    PAGING.paging_csout.bind(paging_csout)
    PAGING.paging_weout.bind(paging_weout)
    PAGING.physical_address.bind(physical_address)
    PAGING.dataout.bind(ram_dataout)
    PAGING.data_valid.bind(icache_valid)
    PAGING.stall_ifu.bind(stall_fetch)
    PAGING.CLK.bind(clk)
    ICACHE = ICache("ICACHE_BLOCK")
    modules.append(ICACHE)
    ICACHE.init_param(2)
    ICACHE.datain.bind(paging_dout)
    ICACHE.cs.bind(paging_csout)
    ICACHE.we.bind(paging_weout)
    ICACHE.addr.bind(physical_address)
    ICACHE.ld_valid.bind(pid_valid)
    ICACHE.ld_data.bind(pid_data)
    ICACHE.dataout.bind(icache_din)
    ICACHE.icache_valid.bind(icache_validin)
    ICACHE.stall_fetch.bind(icache_stall)
    ICACHE.CLK.bind(clk)
    DCACHE = DCache("DCACHE_BLOCK")
    modules.append(DCACHE)
    DCACHE.init_param(2)
    DCACHE.datain.bind(mmic_datain)
    DCACHE.statein.bind(mmic_statein)
    DCACHE.cs.bind(mmic_cs)
    DCACHE.we.bind(mmic_we)
    DCACHE.addr.bind(mmic_addr)
    DCACHE.dest.bind(mmic_dest)
    DCACHE.destout.bind(mmic_destout)
    DCACHE.dataout.bind(mmic_dataout)
    DCACHE.out_valid.bind(mmic_out_valid)
    DCACHE.stateout.bind(mmic_stateout)
    DCACHE.CLK.bind(clk)
    APIC = PIC("PIC_BLOCK")
    modules.append(APIC)
    APIC.ireq0.bind(ireq0)
    APIC.ireq1.bind(ireq1)
    APIC.ireq2.bind(ireq2)
    APIC.ireq3.bind(ireq3)
    APIC.cs.bind(intack_cpu)
    APIC.rd_wr.bind(rd_wr)
    APIC.intack_cpu.bind(intack_cpu)
    APIC.intreq.bind(intreq)
    APIC.intack.bind(intack)
    APIC.vectno.bind(vectno)
    sc.sc_start()
    assert sc.sc_end_of_simulation_invoked()
    assert sc.sc_time_stamp() == sc.sc_time(275, sc.SC_NS)
    assert len(modules) == 10 and len(unused_signals) == 8


if __name__ == "__main__":
    run()
